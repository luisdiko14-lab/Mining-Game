    public BitmapFont(GraphicsDevice graphicsDevice)
    {
        _atlas = new Texture2D(graphicsDevice, Columns * Cell, 6 * Cell);
        var pixels = Enumerable.Repeat(Color.Transparent, Columns * Cell * 6 * Cell).ToArray();
        for (var character = 32; character <= 126; character++)
        {
            var key = char.ToUpperInvariant((char)character);
            if (!Glyphs.TryGetValue(key, out var rows)) continue;
            var index = character - 32;
            var originX = index % Columns * Cell;
            var originY = index / Columns * Cell;
            for (var y = 0; y < rows.Length; y++)
            for (var x = 0; x < rows[y].Length; x++)
                if (rows[y][x] == '1')
                    pixels[(originY + y) * Columns * Cell + originX + x] = Color.White;
        }
        _atlas.SetData(pixels);
    }

    public void Draw(SpriteBatch batch, string text, Vector2 position, Color color, float scale = 2f)
    {
        var cursorX = position.X;
        foreach (var character in text)
        {
            if (character == '\n')
            {
                position.Y += Cell * scale;
                cursorX = position.X;
                continue;
            }
            var key = char.ToUpperInvariant(character);
            if (key is < ' ' or > '~') key = '?';
            var index = key - 32;
            var source = new Rectangle(index % Columns * Cell, index / Columns * Cell, Cell, Cell);
            batch.Draw(_atlas, new Rectangle((int)cursorX, (int)position.Y, (int)(Cell * scale), (int)(Cell * scale)), source, color);
            cursorX += 6 * scale;
        }
    }

    public void Dispose() => _atlas.Dispose();
